#!/usr/bin/env python3
"""Build the root template that Umbrel actually refreshes during app updates."""

from __future__ import annotations

import argparse
import base64
import json
import re
import zlib
from pathlib import Path

WEB_DIRECTORY = Path(__file__).resolve().parent
PACKAGE_DIRECTORY = WEB_DIRECTORY.parent
BUNDLE_PATH = PACKAGE_DIRECTORY / "ui.py.template"
RESOURCE_PATHS = ("app.py", "static/index.html", "static/app.css", "static/app.js")


def build_bundle() -> str:
    manifest = (PACKAGE_DIRECTORY / "umbrel-app.yml").read_text(encoding="utf-8")
    version = re.search(r'^version: "([^"]+)"$', manifest, re.MULTILINE)
    if version is None:
        raise ValueError("Missing quoted package version in umbrel-app.yml")
    resources = {name: (WEB_DIRECTORY / name).read_text(encoding="utf-8") for name in RESOURCE_PATHS}
    payload = base64.b64encode(zlib.compress(
        json.dumps(resources, ensure_ascii=False, sort_keys=True).encode("utf-8"), level=9
    )).decode("ascii")
    # Encoding protects JavaScript template literals from Umbrel's envsubst pass.
    chunks = "\n".join(f'    "{payload[offset:offset + 100]}"' for offset in range(0, len(payload), 100))
    return f'''#!/usr/bin/env python3
# Generated by web/build_bundle.py. Edit web/ sources and regenerate this file.
# Umbrel copies root *.template files on update, but does not refresh web/.
import base64
import json
import os
import runpy
import tempfile
import zlib
from pathlib import Path

VERSION = {version.group(1)!r}
PAYLOAD = (
{chunks}
)


def main():
    resources = json.loads(zlib.decompress(base64.b64decode(PAYLOAD)))
    with tempfile.TemporaryDirectory(prefix="anime365-ui-") as directory:
        root = Path(directory)
        for name, contents in resources.items():
            target = root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(contents, encoding="utf-8")
        os.environ["ANIME365_UI_VERSION"] = VERSION
        runpy.run_path(str(root / "app.py"), run_name="__main__")


if __name__ == "__main__":
    main()
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed bundle is stale")
    args = parser.parse_args()
    generated = build_bundle()
    if args.check:
        if not BUNDLE_PATH.is_file() or BUNDLE_PATH.read_text(encoding="utf-8") != generated:
            parser.exit(1, "ui.py.template is stale; run python3 epsilon-anime365-sidecar/web/build_bundle.py\n")
        print("ui.py.template matches the web sources and package version")
    else:
        BUNDLE_PATH.write_text(generated, encoding="utf-8")
        print(f"Generated {BUNDLE_PATH.name} ({len(generated)} bytes)")


if __name__ == "__main__":
    main()
